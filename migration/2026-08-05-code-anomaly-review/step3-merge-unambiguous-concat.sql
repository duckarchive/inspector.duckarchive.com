-- 1. relink online copies (skip would-be duplicates)
UPDATE online_copies oc SET file_id = p.base_id, updated_at = now()
FROM pairs p
WHERE oc.file_id = p.anomaly_id
  AND NOT EXISTS (
    SELECT 1 FROM online_copies o2
    WHERE o2.file_id = p.base_id AND o2.resource_id = oc.resource_id
      AND o2.parsed = oc.parsed AND o2.url = oc.url);

-- 2. move years / locations / authors that the base lacks
INSERT INTO file_years (file_id, start_year, end_year)
SELECT p.base_id, y.start_year, y.end_year
FROM pairs p JOIN file_years y ON y.file_id = p.anomaly_id
ON CONFLICT DO NOTHING;

INSERT INTO file_locations (lat, lng, radius_m, file_id)
SELECT l.lat, l.lng, l.radius_m, p.base_id
FROM pairs p JOIN file_locations l ON l.file_id = p.anomaly_id
ON CONFLICT DO NOTHING;

INSERT INTO file_authors (file_id, author_id)
SELECT p.base_id, fa.author_id
FROM pairs p JOIN file_authors fa ON fa.file_id = p.anomaly_id
ON CONFLICT DO NOTHING;

-- 3. keep the richer title: copy the anomaly's title onto an untitled base
UPDATE files b SET title = a.title, info = coalesce(b.info, a.info)
FROM pairs p JOIN files a ON a.id = p.anomaly_id
WHERE b.id = p.base_id AND b.title IS NULL AND a.title IS NOT NULL;

-- 4. leftover check — must be 0 rows before the DELETE below is safe
--    (copies that stayed because the base already had an identical one are
--    true duplicates and will be cascade-deleted with the anomaly file)
SELECT count(*) AS copies_still_on_anomalies
FROM online_copies oc JOIN pairs p ON p.anomaly_id = oc.file_id;

-- 5. delete the anomaly files (cascades: remaining duplicate copies, years,
--    locations; file_authors rows are removed explicitly first)
DELETE FROM file_authors fa USING pairs p WHERE fa.file_id = p.anomaly_id;
DELETE FROM files f USING pairs p WHERE f.id = p.anomaly_id;

COMMIT;
